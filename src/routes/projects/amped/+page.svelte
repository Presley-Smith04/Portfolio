Amped is a rhythm based Interactive Gaming experience built using Unity and custom hardware controllers.

The project focused on integrating physical inputs with real time gameplay systems. We achieved this by letting Arduino hardware and Unity software communicate in real time.

I worked on gameplay logic, debugging, communication timing issues, and maintaining reliable responsiveness between systems. (I also created the soundtrack we used for the game)

One challenge we faces was trying to make sure hardware input remained stable and responsive during gameplay while coordinating multiple interactive systems at once.

This project strengthened my understanding of systems level design, hardware/software integration, and immersive interactive experiences.

Amped was later submitted to the Alt Ctrl showcase at GDC, which highlights experimental games using alternative controllers.
