BUCK OFF is a retro inspired rhythm game built in Unity where the player controls a mechanical bull and tries to throw riders off by timing inputs to falling notes.

The project was inspired by rhythm games like Guitar Hero, Dance Dance Revolution, and Friday Night Funkin’, while mixing in a chaotic country western arcade aesthetic. Players use WASD controls to match incoming notes, build score multipliers, and survive as long as possible before the bull malfunctions after too many missed inputs.

I worked heavily on the UI and presentation side of the project, including creating the Start Menu, Credits Menu, Instructions screen, and much of the dialogue and written content throughout the game. I also engineered and worked on almost all of the audio used in the experience, helping shape the overall atmosphere and feel of the game.

One challenge we faced was balancing development across a small team while learning new tools and managing workflow issues like Git conflicts and asset creation. Since multiple systems were being worked on at once, communication and organization became a major part of keeping development moving smoothly.

This project helped strengthen my understanding of UI/UX design, audio implementation, collaborative game development, and creating cohesive player experiences through presentation, interaction, and sound design.
