Ivy is an IoT based interactive plant monitoring system that combines hardware, software, and real time Discord integration to turn a simple plant into a chaotic digital personality.

The project was built using an ESP8266, Node.js, Discord.js, JavaScript, C++, moisture sensors, servo motors, and audio components to allow the plant to monitor itself, communicate through Discord, and even water itself automatically when needed.

I worked on nearly every aspect of the project including the Node.js systems, Discord bot functionality, API communication between the ESP8266 and the bot, command systems, sensor handling, hardware/software integration, and overall project functionality and personality design.

One challenge we faced was figuring out how to reliably connect hardware systems with software systems in real time, especially while dealing with WiFi communication, motor control, Discord integration, and live sensor data all at once.

