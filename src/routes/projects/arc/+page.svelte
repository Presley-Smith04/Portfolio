ARC was an interactive projection mapping installation made with TouchDesigner, MediaPipe, cameras, projectors, and Resolume Arena. People could stand inside a large arc structure and control visuals around them using hand movement and body interaction.

The setup used cameras inside the structure to track movement through MediaPipe in TouchDesigner. This allowed users to interact with generative visuals in real time through gestures.

I mostly worked on the technical side of the project by setting everything up, troubleshooting issues, and making sure all the hardware and software worked together properly. I also helped with parts of the TouchDesigner and MediaPipe setup for the interaction and tracking systems. A large part of my role was making sure the cameras, projectors, and displays stayed connected and running smoothly during the installation.

One of the harder parts was keeping the tracking responsive while multiple systems were running at the same time. Since everything depended on live cameras, visuals, and projectors communicating together, there was a lot of testing, calibration, and debugging involved.

This project taught me a lot about interactive installations, projection mapping, motion tracking, and working with large scale real time visual systems.
